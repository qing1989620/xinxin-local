"""种子技能目录（数据部分）。

技能内容按立理 S1 真实的科研领域与工作流形态编写，遵循 agentskills.io 的
SKILL.md 规范（Claude Code / Google ADK / Cursor / Gemini CLI 通用）。

字段对应论文中的抽象：
- capability / inputs / outputs / use_when  -> Skill Contract (SkillNet-Fabric)
- steps / pitfalls / verification           -> 可执行程序性知识 (DisCo 的 operational knowledge)
- quality                                   -> SkillNet 五维评估
- relations                                 -> Skill Relation Graph 的类型化边
"""
from __future__ import annotations

from typing import Any

RAW: list[dict[str, Any]] = []


def S(
    name: str,
    domain: str,
    desc: str,
    cap: str,
    ins: list[str],
    outs: list[str],
    use_when: list[str],
    steps: list[str],
    pitfalls: list[str],
    verify: list[str],
    tags: list[str],
    rels: list[tuple[str, str]] | None = None,
    q: dict[str, str] | None = None,
) -> None:
    RAW.append(
        dict(
            name=name,
            domain=domain,
            description=desc,
            capability=cap,
            inputs=ins,
            outputs=outs,
            use_when=use_when,
            steps=steps,
            pitfalls=pitfalls,
            verification=verify,
            tags=tags,
            relations=rels or [],
            quality=q
            or {
                "safety": "Good",
                "completeness": "Good",
                "executability": "Average",
                "maintainability": "Good",
                "cost_awareness": "Good",
            },
        )
    )


